#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unknown_locale_falls_back_to_english() {
        assert_eq!(menu_text("xx").quit, "Quit Duolo");
        assert_eq!(language_name("xx"), "English");
        assert_eq!(menu_text("ja").new_task, "新規タスク");
        assert_eq!(language_name("zh-CN"), "Simplified Chinese");
    }
}
